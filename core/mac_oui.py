def lookup_vendor(mac: str | None) -> str | None:
    """Return manufacturer name from MAC or None if unknown."""
    if not mac:
        return None
    mac = mac.strip().lower().replace("-", ":")
    parts = mac.split(":")
    if len(parts) < 3:
        return None
    prefix = ":".join(parts[:3])
    return _OUI_DB.get(prefix)


def is_locally_administered(mac: str | None) -> bool:
    """Check if MAC is locally administered (randomized, privacy MAC)."""
    if not mac:
        return False
    try:
        first_byte = int(mac.split(":")[0], 16)
        return bool(first_byte & 0x02)
    except (ValueError, IndexError):
        return False
